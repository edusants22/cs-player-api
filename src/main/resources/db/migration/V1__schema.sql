CREATE TABLE times (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, nome VARCHAR(100) NOT NULL UNIQUE);
CREATE TABLE jogadores (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nickname VARCHAR(80) NOT NULL UNIQUE, nome_completo VARCHAR(150) NOT NULL,
 idade INTEGER NOT NULL CHECK (idade BETWEEN 13 AND 100), pais VARCHAR(40) NOT NULL,
 time_id BIGINT NOT NULL REFERENCES times(id), funcao VARCHAR(30) NOT NULL,
 arma_favorita VARCHAR(30) NOT NULL, rating DOUBLE PRECISION NOT NULL CHECK (rating >= 0 AND rating <= 5),
 majors INTEGER NOT NULL DEFAULT 0, inicio_carreira DATE
);
